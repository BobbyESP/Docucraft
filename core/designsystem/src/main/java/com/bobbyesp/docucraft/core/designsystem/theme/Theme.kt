/** The type roles Material's [androidx.compose.material3.Typography] has no slot for. */
@Immutable data class DocucraftTypography(val monospace: FontFamily = FontFamily.Monospace)

private val LocalDocucraftTypography = staticCompositionLocalOf { DocucraftTypography() }

/** The app's additions to [androidx.compose.material3.MaterialTheme], read the same way. */
object DocucraftTheme {
    val typography: DocucraftTypography
        @Composable @ReadOnlyComposable get() = LocalDocucraftTypography.current
}

/**
 * The app's theme: Material 3 Expressive, with colors from the wallpaper or generated by
 * MaterialKolor from the user's seed color. A change moves every color of the app to its new one
 * (see [rememberThemeTransition]).
 *
 * @param isDark whether to use the dark scheme; taken from [userPreferences] unless the caller has
 *   already worked it out.
 */
@Suppress("ModifierRequired")
@Composable
fun DocucraftTheme(
    userPreferences: UserPreferences = UserPreferences(),
    isDark: Boolean = userPreferences.themeConfig.isDarkTheme(),
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val motionScheme = MotionScheme.expressive()

    val cache = remember(context) { ColorSchemeCache() }
    val built =
        rememberColorScheme(
            source =
                ColorSchemeSource(
                    isDark = isDark,
                    useWallpaperColors = userPreferences.useDynamicColoring,
                    seedColor = userPreferences.themeSeedColor,
                    paletteStyle = userPreferences.paletteStyle,
                    pureBlack = userPreferences.isHighContrastModeEnabled,
                ),
            cache = cache,
        )
    val transition = rememberThemeTransition(built.scheme)
    // One object for the theme's lifetime: a new one would recompose everything under it.
    val themeColors = remember(cache) { ThemeColors(built, cache) }.apply { this.built = built }

    // A new resolver makes every text lay out again, so it must outlive recompositions.
    val fontFamilyResolver =
        remember(context) {
            val fontHandler = CoroutineExceptionHandler { _, throwable ->
                Log.e("DocucraftTheme", "Error loading font: ${throwable.message}", throwable)
            }
            createFontFamilyResolver(context, fontHandler)
        }

    val displayFont = userPreferences.displayFont.toFontFamily()
    val titleFont = userPreferences.titleFont.toFontFamily()
    val bodyFont = userPreferences.bodyFont.toFontFamily()
    val labelFont = userPreferences.labelFont.toFontFamily()
    val monospaceFont = userPreferences.monospaceFont.toFontFamily() ?: FontFamily.Monospace

    val typography =
        remember(displayFont, titleFont, bodyFont, labelFont) {
            createTypography(
                displayFont = displayFont,
                titleFont = titleFont,
                bodyFont = bodyFont,
                labelFont = labelFont,
            )
        }
    val docucraftTypography = remember(monospaceFont) { DocucraftTypography(monospaceFont) }

    CompositionLocalProvider(
        LocalFontFamilyResolver provides fontFamilyResolver,
        LocalDocucraftTypography provides docucraftTypography,
        LocalThemeColors provides themeColors,
    ) {
        MaterialExpressiveTheme(
            colorScheme = transition.colorScheme,
            motionScheme = transition.motionScheme(motionScheme),
            typography = typography,
            content = content,
        )
    }
}

/**
 * The app's theme around one color, for a screen about something the user gave a color to: only
 * [content] takes it, once per color, never stepped towards it. The color is a hue, built as
 * [AccentPaletteStyle] beside the app's primary, black where the app's surfaces are. See
 * `docs/architecture.md`, Theme.
 *
 * @param accent The color, or `null` for none, which leaves the app's theme as it is. It may come
 *   and go while [content] stays.
 */
@Suppress("ModifierRequired")
@Composable
fun DocucraftAccentTheme(accent: Color?, content: @Composable () -> Unit) {
    val appScheme = MaterialTheme.colorScheme
    val themeColors = LocalThemeColors.current

    val scheme =
        if (accent != null && themeColors != null) {
            val built = themeColors.built
            val source = remember(accent, built) { built.accentSource(accent) }
            rememberColorScheme(
                    source = source,
                    cache = themeColors.cache,
                    placeholder = appScheme,
                )
                .scheme
        } else {
            appScheme
        }

    MaterialExpressiveTheme(
        colorScheme = scheme,
        motionScheme = MaterialTheme.motionScheme,
        shapes = MaterialTheme.shapes,
        typography = MaterialTheme.typography,
        content = content,
    )
}

/**
 * Builds the schemes [DocucraftAccentTheme] would build for [accents], in the background, so that a
 * screen in one of them opens in it rather than switching once it is built.
 *
 * Starts again for each change of the app's theme, after it has settled, and builds one scheme at a
 * time. Belongs under the app's theme, once; [accents] should be the same list on every call.
 */
@Composable
fun PrepareAccentThemes(accents: List<Color>) {
    val themeColors = LocalThemeColors.current ?: return
    val context = LocalContext.current
    val built = themeColors.built
    LaunchedEffect(themeColors, built, accents) {
        // A burst of changes, as when tapping through seed colors, builds nothing for the
        // intermediate ones.
        delay(PrepareDelayMillis.milliseconds)
        for (accent in accents) {
            val source = built.accentSource(accent)
            if (themeColors.cache[source] != null) continue
            val scheme = withContext(Dispatchers.Default) { source.build(context) }
            themeColors.cache[source] = scheme
        }
    }
}

// Harmonized with the scheme the app is heading to, not the step it is at: a change of theme
// asks for one new scheme, not one per step. Black follows what the app shows, not the setting:
// the system's scheme, with dynamic color, is never black.
private fun BuiltColorScheme.accentSource(accent: Color): ColorSchemeSource =
    source.copy(
        useWallpaperColors = false,
        seedColor = Blend.harmonize(accent.toArgb(), scheme.primary.toArgb()),
        paletteStyle = AccentPaletteStyle,
        pureBlack = scheme.background == Color.Black,
    )

private const val PrepareDelayMillis = 1_000L

@Immutable
internal data class ColorSchemeSource(
    val isDark: Boolean,
    val useWallpaperColors: Boolean,
    val seedColor: Int,
    val paletteStyle: PaletteStyleConfig,
    val pureBlack: Boolean,
)

/** A scheme with what it was built from: the two are only ever read together. */
@Immutable internal class BuiltColorScheme(val source: ColorSchemeSource, val scheme: ColorScheme)

/**
 * What a theme nested in the app's needs to build a scheme of its own in keeping with it: the
 * scheme the app is in, or heading to, and what it was built from.
 */
@Stable
internal class ThemeColors(built: BuiltColorScheme, val cache: ColorSchemeCache) {
    /** State, not a new object per scheme: only what reads it recomposes when it changes. */
    var built: BuiltColorScheme by mutableStateOf(built)
}

private val LocalThemeColors = staticCompositionLocalOf<ThemeColors?> { null }

private fun ColorSchemeSource.build(context: Context): ColorScheme =
    if (useWallpaperColors && isDynamicColoringSupported()) {
        if (isDark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
    } else {
        dynamicColorScheme(
            seedColor = Color(seedColor),
            isDark = isDark,
            isAmoled = pureBlack,
            specVersion = DocucraftColorSpec,
            style = paletteStyle.toPaletteStyle(),
        )
    }

/**
 * The color scheme for [source], built only when it changes. Generating one takes milliseconds, so
 * each change is built in the background, and the scheme before it stays until it is ready.
 *
 * @param placeholder What to show while the first scheme is built. Without one the first is built
 *   in place, as the app's has to be: its first frame needs it.
 */
@Composable
private fun rememberColorScheme(
    source: ColorSchemeSource,
    cache: ColorSchemeCache,
    placeholder: ColorScheme? = null,
): BuiltColorScheme {
    val context = LocalContext.current
    // A preview is one frame: it shows what the theme arrives at, not what it starts from.
    val waitsForIt = placeholder != null && !LocalInspectionMode.current
    var built by
        remember(cache) {
            val scheme =
                cache[source]
                    ?: placeholder.takeIf { waitsForIt }
                    ?: source.build(context).also { cache[source] = it }
            mutableStateOf(BuiltColorScheme(source, scheme))
        }
    LaunchedEffect(cache, source) {
        val scheme =
            cache[source]
                ?: withContext(Dispatchers.Default) { source.build(context) }
                    .also { cache[source] = it }
        if (built.source != source || built.scheme !== scheme) {
            built = BuiltColorScheme(source, scheme)
        }
    }
    return built
}

/** Only ever touched on the main thread: a scheme is built off it, and kept from it. */
internal class ColorSchemeCache :
    LinkedHashMap<ColorSchemeSource, ColorScheme>(CACHED_SCHEMES, 0.75f, true) {
    override fun removeEldestEntry(
        eldest: MutableMap.MutableEntry<ColorSchemeSource, ColorScheme>
    ) = size > CACHED_SCHEMES
}

// Light and dark of the current colors and of the previous ones, and the palette's colors that
// PrepareAccentThemes builds, in both.
private const val CACHED_SCHEMES = 32

/** Shared by the theme and the palette previews, so a preview shows what the theme applies. */
internal val DocucraftColorSpec = ColorSpec.SpecVersion.SPEC_2025

/**
 * The style of a screen's own color ([DocucraftAccentTheme]): Material's default, Tonal Spot, whose
 * calm tones suit a color picked to tell things apart. Its chroma is [accentChroma].
 */
internal val AccentPaletteStyle = PaletteStyleConfig.TonalSpot

/**
 * The chroma of [AccentPaletteStyle]'s primary tones in [DocucraftColorSpec] on a phone, so that a
 * color shown outside its own theme, such as a folder's badge, matches the screen it opens.
 */
fun accentChroma(isDark: Boolean): Double = if (isDark) 26.0 else 32.0
